#!/usr/bin/env python3
"""Generate the host reverse-proxy config for tenant boxes (Epic C, C1).

The proxy is the only public front door (design §13.3, §14.1): it routes
by Host header (subdomain) to exactly one tenant box, and drops every
unknown host. Tenants never share a process, and the proxy never serves
a tenant from another tenant's upstream.

Usage:
    python3 scripts/generate_proxy_config.py tenants.json [--tls] [--out FILE]

tenants.json: {"<subdomain>": <frontend host port>, ...}, e.g.
    {"qgbs.example.com": 5173, "na.example.com": 5174}

Modes:
- Interim (default, no --tls): plain-HTTP server blocks. This is for
  testing BEFORE a custom domain exists: boxes are reached directly
  by IP:port, and the proxy file is generated and validated now so
  the subdomain cutover is a config swap, not new work.
- --tls: HTTPS blocks with Let's Encrypt certificate paths
  (/etc/letsencrypt/live/<subdomain>/...) plus HTTP -> HTTPS redirect
  blocks. Use only once the domain exists and certbot has issued the
  certificates (see docs/multi-tenancy-runbook.md).

Every tenant block forwards the WebSocket upgrade headers: the box's
own frontend nginx needs them for the Browser Test stream, and an
outer proxy that strips them would break it exactly like the
October 23 nginx bug did.

Unknown hosts: the default server returns 444 (close, no response)
rather than serving any tenant — a guessed subdomain must never land
on a tenant's login page.
"""
import argparse
import json
import re
import sys

_SLUG = re.compile(r"^[a-z0-9][a-z0-9.-]*[a-z0-9]$")


def validate_tenants(raw):
    """Return a sorted {subdomain: port} map or raise ValueError."""
    if not isinstance(raw, dict) or not raw:
        raise ValueError("tenants.json must be a non-empty object")
    out = {}
    for host, port in raw.items():
        if not isinstance(host, str) or not _SLUG.match(host):
            raise ValueError(f"invalid subdomain: {host!r}")
        if not isinstance(port, int) or not (1 <= port <= 65535):
            raise ValueError(f"invalid port for {host!r}: {port!r}")
        out[host] = port
    if len(set(out.values())) != len(out):
        raise ValueError("two subdomains share one frontend port")
    return dict(sorted(out.items()))


def render(tenants, tls):
    lines = []
    lines.append("# Generated by scripts/generate_proxy_config.py — do not hand-edit.")
    lines.append("# Regenerate after every tenant add/remove; the file is the")
    lines.append("# routing table, and a stale table is a misrouting risk.")
    lines.append("")
    # Default server: unknown hosts get nothing, not a tenant.
    lines.append("# Unknown host: close the connection, serve no tenant.")
    lines.append("server {")
    lines.append("    listen 80 default_server;")
    if tls:
        lines.append("    listen 443 ssl default_server;")
        lines.append("    ssl_reject_handshake on;")
    lines.append("    server_name _;")
    lines.append("    return 444;")
    lines.append("}")
    for host, port in tenants.items():
        upstream = f"127.0.0.1:{port}"
        lines.append("")
        if tls:
            lines.append(f"# {host} -> box frontend {upstream} (HTTPS)")
            lines.append("server {")
            lines.append("    listen 80;")
            lines.append(f"    server_name {host};")
            lines.append("    return 301 https://$host$request_uri;")
            lines.append("}")
            lines.append("server {")
            lines.append("    listen 443 ssl;")
            lines.append(f"    server_name {host};")
            lines.append(f"    ssl_certificate /etc/letsencrypt/live/{host}/fullchain.pem;")
            lines.append(f"    ssl_certificate_key /etc/letsencrypt/live/{host}/privkey.pem;")
        else:
            lines.append(f"# {host} -> box frontend {upstream} (INTERIM HTTP: no domain yet)")
            lines.append("server {")
            lines.append("    listen 80;")
            lines.append(f"    server_name {host};")
        lines.append("    location / {")
        lines.append(f"        proxy_pass http://{upstream};")
        lines.append("        proxy_http_version 1.1;")
        lines.append('        proxy_set_header Upgrade $http_upgrade;')
        lines.append('        proxy_set_header Connection "upgrade";')
        lines.append("        proxy_set_header Host $host;")
        lines.append("        proxy_set_header X-Real-IP $remote_addr;")
        lines.append("        proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;")
        lines.append("        proxy_set_header X-Forwarded-Proto $scheme;")
        lines.append("        proxy_read_timeout 3600s;")
        lines.append("    }")
        lines.append("}")
    return "\n".join(lines) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("map", help="JSON file: {subdomain: frontend host port}")
    ap.add_argument("--tls", action="store_true",
                    help="emit HTTPS blocks with Let's Encrypt paths")
    ap.add_argument("--out", default="-", help="output file, - = stdout")
    args = ap.parse_args(argv)
    try:
        with open(args.map) as f:
            tenants = validate_tenants(json.load(f))
    except (OSError, ValueError, json.JSONDecodeError) as exc:
        print(f"generate_proxy_config: {exc}", file=sys.stderr)
        return 2
    text = render(tenants, args.tls)
    if args.out == "-":
        sys.stdout.write(text)
    else:
        with open(args.out, "w") as f:
            f.write(text)
    print(f"generate_proxy_config: {len(tenants)} tenant(s), "
          f"{'TLS' if args.tls else 'interim HTTP'}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
