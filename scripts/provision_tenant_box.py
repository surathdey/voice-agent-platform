#!/usr/bin/env python3
"""Provision ONE Secure Box's environment file (Epic C, story C1).

A box's secrets live in exactly one file: boxes/<slug>.env (mode 0600).
The script generates what must be unique per box and refuses to
overwrite an existing box unless --force is given — overwriting an
env file would orphan the box's database credentials.

Usage (from the repo root):
    python3 scripts/provision_tenant_box.py --slug na \
        --tenant-name "North America" --market NA \
        --frontend-port 5174 --backend-port 8001

Then start the box:
    docker compose -f docker-compose.tenant.yml -p vap-na \
        --env-file boxes/na.env up -d --build

What is generated per box (never shared, never copied from another box):
- POSTGRES_USER / POSTGRES_DB: derived from the slug.
- POSTGRES_PASSWORD, SECRET_KEY, SEED_USER_PASSWORD: fresh random
  values. The seed password is printed ONCE below — record it in the
  tenant's secret store now; it is not printed again and not stored
  anywhere else by this script.
- BOX_TENANT_SLUG, SEED_TENANT_NAME, SEED_USER_EMAIL: identity.
- TELEPHONY_MODE defaults to stub: a C1 box boots and tests with no
  provider keys. Real keys are added to the box env file later, per
  tenant, never to a shared file.

What this script does NOT do: it does not start Docker (this repo's
dev VM has none), does not touch any other box, and does not write
to the live stack. If a `docker` binary is present it validates the
generated env against docker-compose.tenant.yml (`config -q`) without
starting anything.
"""
import argparse
import os
import re
import secrets
import shutil
import stat
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SLUG_RE = re.compile(r"^[a-z0-9][a-z0-9-]*[a-z0-9]$")


def fail(msg):
    print(f"provision_tenant_box: {msg}", file=sys.stderr)
    return 2


def main(argv=None):
    ap = argparse.ArgumentParser(description="Provision one tenant box env file")
    ap.add_argument("--slug", required=True,
                    help="box slug, e.g. na (lowercase letters/digits/hyphens)")
    ap.add_argument("--tenant-name", required=True,
                    help="seed tenant display name, e.g. 'North America'")
    ap.add_argument("--market", default="NA",
                    help="market code for the seed tenant (default NA)")
    ap.add_argument("--frontend-port", required=True, type=int)
    ap.add_argument("--backend-port", required=True, type=int)
    ap.add_argument("--out-dir", default=os.path.join(ROOT, "boxes"),
                    help="directory for the env file (default ./boxes)")
    ap.add_argument("--telephony-mode", default="stub",
                    help="TELEPHONY_MODE for the box (default stub)")
    ap.add_argument("--public-base-url", default="",
                    help="PUBLIC_BASE_URL override (default http://localhost:<backend-port>)")
    ap.add_argument("--force", action="store_true",
                    help="overwrite an existing env file for this slug")
    args = ap.parse_args(argv)

    slug = args.slug.strip().lower()
    if not SLUG_RE.match(slug):
        return fail(f"invalid slug {slug!r}: use lowercase letters, digits, hyphens")
    for port, name in ((args.frontend_port, "frontend"), (args.backend_port, "backend")):
        if not (1024 <= port <= 65535):
            return fail(f"invalid {name} port {port}: use 1024-65535")
    if args.frontend_port == args.backend_port:
        return fail("frontend and backend ports must differ")

    os.makedirs(args.out_dir, exist_ok=True)
    env_path = os.path.join(args.out_dir, f"{slug}.env")
    if os.path.exists(env_path) and not args.force:
        return fail(f"{env_path} already exists — refusing to overwrite "
                    "(re-run with --force only if you mean to orphan the "
                    "old box's credentials)")

    pg_suffix = slug.replace("-", "_")
    public_base = args.public_base_url or f"http://localhost:{args.backend_port}"
    lines = [
        f"# Secure Box env for tenant '{slug}' — generated by provision_tenant_box.py.",
        "# One file per box; never copy secrets between boxes.",
        f"COMPOSE_PROJECT_NAME=vap-{slug}",
        f"POSTGRES_USER=vap_{pg_suffix}",
        f"POSTGRES_PASSWORD={secrets.token_urlsafe(24)}",
        f"POSTGRES_DB=voice_platform_{pg_suffix}",
        f"SECRET_KEY={secrets.token_hex(32)}",
        f"TELEPHONY_MODE={args.telephony_mode}",
        f"BOX_TENANT_SLUG={slug}",
        f"SEED_TENANT_NAME={args.tenant_name}",
        f"SEED_USER_EMAIL=admin@{slug}.example",
        f"SEED_USER_PASSWORD={secrets.token_urlsafe(16)}",
        f"SEED_USER_NAME=Box Admin",
        f"FRONTEND_PORT={args.frontend_port}",
        f"BACKEND_PORT={args.backend_port}",
        f"PUBLIC_BASE_URL={public_base}",
        "WEBHOOK_SECRET=",
        "# Provider keys: empty until this tenant's own keys are supplied.",
        "VAPI_API_KEY=",
        "VAPI_PHONE_NUMBER_ID=",
        "VAPI_SERVER_CREDENTIAL_ID=",
        "TWILIO_ACCOUNT_SID=",
        "TWILIO_AUTH_TOKEN=",
        "PLIVO_AUTH_ID=",
        "PLIVO_AUTH_TOKEN=",
        "EXOTEL_SID=",
        "EXOTEL_API_KEY=",
        "EXOTEL_API_TOKEN=",
        "EXOTEL_SUBDOMAIN=",
        "SARVAM_API_KEY=",
        "S3_RECORDINGS_BUCKET=",
    ]
    with open(env_path, "w") as f:
        f.write("\n".join(lines) + "\n")
    os.chmod(env_path, stat.S_IRUSR | stat.S_IWUSR)

    seed_password = [ln for ln in lines if ln.startswith("SEED_USER_PASSWORD=")][0].split("=", 1)[1]
    print(f"Box '{slug}' provisioned: {env_path} (mode 0600)")
    print(f"  project: vap-{slug}   frontend :{args.frontend_port}   "
          f"backend 127.0.0.1:{args.backend_port}")
    print(f"  seed login: admin@{slug}.example / {seed_password}")
    print("  RECORD THE SEED PASSWORD NOW — it is printed only here.")
    print("  Start it with:")
    print(f"    docker compose -f docker-compose.tenant.yml -p vap-{slug} \\")
    print(f"        --env-file {env_path} up -d --build")
    print(f"  Verify with: curl http://localhost:{args.frontend_port}/api/health"
          "  (via the frontend proxy)")

    if shutil.which("docker"):
        cmd = ["docker", "compose", "-f",
               os.path.join(ROOT, "docker-compose.tenant.yml"),
               "-p", f"vap-{slug}", "--env-file", env_path, "config", "-q"]
        r = subprocess.run(cmd, capture_output=True, text=True)
        if r.returncode == 0:
            print("  docker compose config: OK (template validates with this env)")
        else:
            print("  WARNING: docker compose config failed:")
            print(r.stderr.strip()[:1000])
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
